create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique,
  created_at timestamptz not null default now()
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  receiver_id uuid not null references public.profiles(id) on delete cascade,
  content text not null default '',
  attachment_path text,
  attachment_name text,
  created_at timestamptz not null default now(),
  constraint messages_not_empty check (length(trim(content)) > 0 or attachment_path is not null),
  constraint messages_no_self check (sender_id <> receiver_id)
);

create index if not exists messages_pair_created_idx
on public.messages (sender_id, receiver_id, created_at);

create or replace function public.block_create_profile()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  chosen_username text;
begin
  chosen_username := nullif(trim(new.raw_user_meta_data ->> 'username'), '');
  if chosen_username is null then
    chosen_username := split_part(new.email, '@', 1);
  end if;
  insert into public.profiles (id, username)
  values (new.id, chosen_username);
  return new;
end;
$$;

drop trigger if exists block_auth_user_created on auth.users;
create trigger block_auth_user_created
after insert on auth.users
for each row execute procedure public.block_create_profile();

alter table public.profiles enable row level security;
alter table public.messages enable row level security;

drop policy if exists "Authenticated users can view profiles" on public.profiles;
create policy "Authenticated users can view profiles"
on public.profiles for select to authenticated
using (true);

drop policy if exists "Users can update their own profile" on public.profiles;
create policy "Users can update their own profile"
on public.profiles for update to authenticated
using (id = (select auth.uid()))
with check (id = (select auth.uid()));

drop policy if exists "Chat participants can read messages" on public.messages;
create policy "Chat participants can read messages"
on public.messages for select to authenticated
using (sender_id = (select auth.uid()) or receiver_id = (select auth.uid()));

drop policy if exists "Users can send messages as themselves" on public.messages;
create policy "Users can send messages as themselves"
on public.messages for insert to authenticated
with check (sender_id = (select auth.uid()) and receiver_id <> (select auth.uid()));

insert into storage.buckets (id, name, public, file_size_limit)
values ('block-files', 'block-files', false, 20971520)
on conflict (id) do update set public = false, file_size_limit = 20971520;

drop policy if exists "Chat users can upload their own files" on storage.objects;
create policy "Chat users can upload their own files"
on storage.objects for insert to authenticated
with check (bucket_id = 'block-files' and (storage.foldername(name))[1] = (select auth.uid())::text);

drop policy if exists "Chat participants can read shared files" on storage.objects;
create policy "Chat participants can read shared files"
on storage.objects for select to authenticated
using (
  bucket_id = 'block-files'
  and (
    (storage.foldername(name))[1] = (select auth.uid())::text
    or exists (
      select 1 from public.messages m
      where m.attachment_path = name
        and (m.sender_id = (select auth.uid()) or m.receiver_id = (select auth.uid()))
    )
  )
);

do $$
begin
  alter publication supabase_realtime add table public.messages;
exception
  when duplicate_object then null;
  when undefined_object then null;
end $$;
